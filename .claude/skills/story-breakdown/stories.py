#!/usr/bin/env python3
"""Turn Annual Plan epics into fine-grained stories inside the planning workbook.

    stories.py epics                      # dump epics + sprint capacity as JSON
    stories.py write --input FILE.json    # (re)build the 'Stories' tab from that file
    stories.py check                      # reconcile stories against epics and capacity

The workbook's formulas carry no cached values until Excel or Sheets opens the file,
so every number here is recomputed from the input cells by planning/plan_lib.py.
Writing re-creates the Dashboard chart, which openpyxl would otherwise drop.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
PLANNING = REPO / "planning"
sys.path.insert(0, str(PLANNING))

from plan_lib import add_dashboard_chart, read_model  # noqa: E402

from openpyxl import load_workbook                     # noqa: E402
from openpyxl.formatting.rule import CellIsRule        # noqa: E402
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side  # noqa: E402
from openpyxl.worksheet.datavalidation import DataValidation  # noqa: E402

WB = PLANNING / "FY2027-sprint-plan-baseline.xlsx"
SHEET = "Stories"
FONT = "Arial"
NAVY = "1F3864"; BAND = "DCE6F1"; GREY = "F2F2F2"; BLUE_TXT = "0000FF"; GREEN_TXT = "008000"
NUM_PTS = '#,##0.0;(#,##0.0);-'
NUM_INT = '#,##0;(#,##0);-'
NUM_PCT = '0.0%;(0.0%);-'
POINT_SCALE = [1, 2, 3, 5, 8]
TOLERANCE = 0.10          # story points may differ from the epic estimate by this much
MAX_STORY_POINTS = 8      # anything larger is an epic in disguise

THIN = Side(style="thin", color="BFBFBF")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
AP_ID = "'Annual Plan'!$A$4:$A$23"
SP_ID = "'Sprint Plan'!$A$4:$A$20"


def F(sz=10, b=False, color="000000", it=False):
    return Font(name=FONT, size=sz, bold=b, color=color, italic=it)


def header(ws, row, headers):
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = F(10, True, "FFFFFF")
        c.fill = PatternFill("solid", fgColor=NAVY)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BOX
    ws.row_dimensions[row].height = 32


# ---------------------------------------------------------------- epics
def cmd_epics(args):
    m = read_model(WB)
    out = dict(
        workbook=m["workbook"], source=m["source"], cadence=m["cadence"], levers=m["levers"],
        totals=m["totals"],
        point_scale=POINT_SCALE, max_story_points=MAX_STORY_POINTS, reconcile_tolerance=TOLERANCE,
        epics=[{k: e[k] for k in ("id", "name", "workstream", "priority", "owner", "estimate",
                                  "confidence", "risk_adjusted", "quarter", "start_sprint",
                                  "end_sprint", "spans", "points_per_sprint", "status")}
               for e in m["epics"]],
        sprints=[{k: s[k] for k in ("n", "label", "quarter", "start", "end", "working_days",
                                    "commitable_pts", "planned_from_epics", "load")}
                 for s in m["sprints"]],
    )
    print(json.dumps(out, indent=2))
    return 0


# ---------------------------------------------------------------- write
def cmd_write(args):
    data = json.loads(Path(args.input).read_text())
    stories = data["stories"] if isinstance(data, dict) else data
    m = read_model(WB)
    epics = {e["id"]: e for e in m["epics"]}
    sprints = {s["n"]: s for s in m["sprints"]}

    bad = [s for s in stories if s.get("epic") not in epics]
    if bad:
        print(f"error: {len(bad)} story/stories name an epic that is not on 'Annual Plan': "
              f"{sorted({s.get('epic') for s in bad})}", file=sys.stderr)
        return 2

    # stable per-epic numbering, in the order the epics appear on Annual Plan
    order = {eid: i for i, eid in enumerate(epics)}
    stories = sorted(stories, key=lambda s: (order[s["epic"]], s.get("sprint") or 0))
    seq: dict[str, int] = {}
    for s in stories:
        seq[s["epic"]] = seq.get(s["epic"], 0) + 1
        s["_id"] = f"{s['epic']}-S{seq[s['epic']]:02d}"

    wb = load_workbook(WB)
    if SHEET in wb.sheetnames:
        del wb[SHEET]
    ws = wb.create_sheet(SHEET, wb.sheetnames.index("Annual Plan") + 1)
    ws.sheet_properties.tabColor = "ED7D31"
    ws.sheet_view.showGridLines = False

    ws["A1"] = "Stories — Fine-Grained Breakdown of the Annual Plan Epics"
    ws["A1"].font = F(14, True, NAVY)
    ws["A2"] = ("Generated by .claude/skills/story-breakdown. Epic, Workstream and Sprint are lookups; "
                "Points, Target Sprint, Status and Notes are yours to edit. Story points reconcile against the "
                "epic ESTIMATE, not its risk-adjusted size — risk adjustment covers what the breakdown cannot see.")
    ws["A2"].font = F(9, color="595959", it=True)

    for col, w in {"A": 14, "B": 10, "C": 30, "D": 58, "E": 62, "F": 21, "G": 9,
                   "H": 13, "I": 9, "J": 13, "K": 34}.items():
        ws.column_dimensions[col].width = w
    header(ws, 3, ["Story ID", "Epic ID", "Epic", "Story", "Acceptance Criteria",
                   "Workstream", "Points", "Target Sprint #", "Sprint", "Status", "Notes"])

    r0 = 4
    r1 = r0 + len(stories) - 1
    for i, s in enumerate(stories):
        r = r0 + i
        a = ws.cell(row=r, column=1, value=s["_id"]); a.font = F(10, True); a.border = BOX
        b = ws.cell(row=r, column=2, value=s["epic"]); b.font = F(10, color=BLUE_TXT); b.border = BOX
        b.alignment = Alignment(horizontal="center")
        c = ws.cell(row=r, column=3,
                    value=f'=IFERROR(INDEX(\'Annual Plan\'!$B$4:$B$23,MATCH($B{r},{AP_ID},0)),"")')
        c.font = F(10, color=GREEN_TXT); c.border = BOX
        c.alignment = Alignment(vertical="top", wrap_text=True)
        d = ws.cell(row=r, column=4, value=s.get("story", "")); d.font = F(10, color=BLUE_TXT)
        d.border = BOX; d.alignment = Alignment(vertical="top", wrap_text=True)
        e = ws.cell(row=r, column=5, value=s.get("acceptance", "")); e.font = F(9, color=BLUE_TXT)
        e.border = BOX; e.alignment = Alignment(vertical="top", wrap_text=True)
        f = ws.cell(row=r, column=6,
                    value=f'=IFERROR(INDEX(\'Annual Plan\'!$C$4:$C$23,MATCH($B{r},{AP_ID},0)),"")')
        f.font = F(10, color=GREEN_TXT); f.border = BOX
        g = ws.cell(row=r, column=7, value=s.get("points")); g.font = F(10, True, BLUE_TXT)
        g.border = BOX; g.number_format = NUM_PTS; g.alignment = Alignment(horizontal="center")
        h = ws.cell(row=r, column=8, value=s.get("sprint")); h.font = F(10, color=BLUE_TXT)
        h.border = BOX; h.number_format = NUM_INT; h.alignment = Alignment(horizontal="center")
        ii = ws.cell(row=r, column=9,
                     value=f'=IFERROR(INDEX(\'Sprint Plan\'!$B$4:$B$20,MATCH($H{r},{SP_ID},0)),"")')
        ii.font = F(10, b=True, color=GREEN_TXT); ii.border = BOX
        ii.alignment = Alignment(horizontal="center")
        j = ws.cell(row=r, column=10, value=s.get("status", "Ready")); j.font = F(10, color=BLUE_TXT)
        j.border = BOX; j.alignment = Alignment(horizontal="center")
        k = ws.cell(row=r, column=11, value=s.get("notes", "")); k.font = F(9, color=BLUE_TXT)
        k.border = BOX; k.alignment = Alignment(vertical="top", wrap_text=True)
        if i % 2:
            for cc in range(1, 12):
                ws.cell(row=r, column=cc).fill = PatternFill("solid", fgColor=BAND)
        ws.row_dimensions[r].height = 30

    tot = r1 + 1
    ws.cell(row=tot, column=3, value="TOTAL story points").font = F(10, True)
    c = ws.cell(row=tot, column=7, value=f"=SUM($G${r0}:$G${r1})")
    c.font = F(10, True); c.number_format = NUM_PTS; c.border = BOX
    c.fill = PatternFill("solid", fgColor=GREY); c.alignment = Alignment(horizontal="center")
    ws.cell(row=tot, column=11, value=f"{len(stories)} stories across {len({s['epic'] for s in stories})} epics").font = F(9, color="404040")

    dv_p = DataValidation(type="list", formula1=f'"{",".join(str(p) for p in POINT_SCALE)}"', allow_blank=True)
    dv_s = DataValidation(type="list", formula1='"Ready,In Progress,Blocked,Done,Parked"', allow_blank=True)
    ws.add_data_validation(dv_p); dv_p.add(f"G{r0}:G{r1}")
    ws.add_data_validation(dv_s); dv_s.add(f"J{r0}:J{r1}")

    # ---- epic reconciliation ----
    used = [eid for eid in epics if any(s["epic"] == eid for s in stories)]
    er0 = tot + 3
    ws.cell(row=er0 - 1, column=1, value="Epic reconciliation — do the stories add up to the epic?").font = F(11, True, NAVY)
    header(ws, er0, ["Epic ID", "Epic", "Estimate (pts)", "Story Points", "Variance (pts)",
                     "Variance %", "Stories", "Risk-Adjusted (pts)", "", "", ""])
    for i, eid in enumerate(used):
        r = er0 + 1 + i
        a = ws.cell(row=r, column=1, value=eid); a.font = F(10, True); a.border = BOX
        b = ws.cell(row=r, column=2,
                    value=f'=IFERROR(INDEX(\'Annual Plan\'!$B$4:$B$23,MATCH($A{r},{AP_ID},0)),"")')
        b.font = F(10, color=GREEN_TXT); b.border = BOX
        c = ws.cell(row=r, column=3,
                    value=f'=IFERROR(INDEX(\'Annual Plan\'!$F$4:$F$23,MATCH($A{r},{AP_ID},0)),"")')
        c.font = F(10, color=GREEN_TXT); c.border = BOX; c.number_format = NUM_PTS
        d = ws.cell(row=r, column=4, value=f"=SUMIFS($G${r0}:$G${r1},$B${r0}:$B${r1},$A{r})")
        d.font = F(10, True); d.border = BOX; d.number_format = NUM_PTS
        e = ws.cell(row=r, column=5, value=f'=IF($C{r}="","",$D{r}-$C{r})')
        e.font = F(10); e.border = BOX; e.number_format = NUM_PTS
        f = ws.cell(row=r, column=6, value=f'=IF(OR($C{r}="",$C{r}=0),"",$E{r}/$C{r})')
        f.font = F(10, True); f.border = BOX; f.number_format = NUM_PCT
        g = ws.cell(row=r, column=7, value=f"=COUNTIFS($B${r0}:$B${r1},$A{r})")
        g.font = F(10); g.border = BOX; g.number_format = NUM_INT
        h = ws.cell(row=r, column=8,
                    value=f'=IFERROR(INDEX(\'Annual Plan\'!$H$4:$H$23,MATCH($A{r},{AP_ID},0)),"")')
        h.font = F(10, color=GREEN_TXT); h.border = BOX; h.number_format = NUM_PTS
        for cc in (3, 4, 5, 6, 7, 8):
            ws.cell(row=r, column=cc).alignment = Alignment(horizontal="center")
    er1 = er0 + len(used)
    ws.conditional_formatting.add(
        f"F{er0+1}:F{er1}",
        CellIsRule(operator="notBetween", formula=[f"-{TOLERANCE}", f"{TOLERANCE}"],
                   fill=PatternFill("solid", fgColor="FFC7CE"), font=F(10, True, "9C0006")))
    ws.cell(row=er1 + 1, column=2,
            value=f"Variance outside +/-{TOLERANCE:.0%} is flagged red: either the breakdown found scope the "
                  "estimate missed, or a story is mis-sized. Fix the estimate on 'Annual Plan' or the story, "
                  "not this formula.").font = F(9, color="404040", it=True)

    # ---- sprint reconciliation ----
    sr0 = er1 + 4
    ws.cell(row=sr0 - 1, column=1, value="Sprint reconciliation — do the assigned stories fit the sprint?").font = F(11, True, NAVY)
    header(ws, sr0, ["Sprint #", "Sprint", "Quarter", "Commitable (pts)", "Story Points Assigned",
                     "Load %", "Stories", "", "", "", ""])
    assigned = sorted({s["sprint"] for s in stories if s.get("sprint")})
    for i, n in enumerate(assigned):
        r = sr0 + 1 + i
        a = ws.cell(row=r, column=1, value=n); a.font = F(10, True); a.border = BOX
        b = ws.cell(row=r, column=2,
                    value=f'=IFERROR(INDEX(\'Sprint Plan\'!$B$4:$B$20,MATCH($A{r},{SP_ID},0)),"")')
        b.font = F(10, True, GREEN_TXT); b.border = BOX
        c = ws.cell(row=r, column=3,
                    value=f'=IFERROR(INDEX(\'Sprint Plan\'!$C$4:$C$20,MATCH($A{r},{SP_ID},0)),"")')
        c.font = F(10, color=GREEN_TXT); c.border = BOX
        d = ws.cell(row=r, column=4,
                    value=f'=IFERROR(INDEX(\'Sprint Plan\'!$K$4:$K$20,MATCH($A{r},{SP_ID},0)),"")')
        d.font = F(10, color=GREEN_TXT); d.border = BOX; d.number_format = NUM_PTS
        e = ws.cell(row=r, column=5, value=f"=SUMIFS($G${r0}:$G${r1},$H${r0}:$H${r1},$A{r})")
        e.font = F(10, True); e.border = BOX; e.number_format = NUM_PTS
        f = ws.cell(row=r, column=6, value=f'=IF(OR($D{r}="",$D{r}=0),"",$E{r}/$D{r})')
        f.font = F(10, True); f.border = BOX; f.number_format = NUM_PCT
        g = ws.cell(row=r, column=7, value=f"=COUNTIFS($H${r0}:$H${r1},$A{r})")
        g.font = F(10); g.border = BOX; g.number_format = NUM_INT
        for cc in range(1, 8):
            ws.cell(row=r, column=cc).alignment = Alignment(horizontal="center")
    sr1 = sr0 + len(assigned)
    for rule in (
        CellIsRule(operator="greaterThan", formula=["1"], fill=PatternFill("solid", fgColor="FFC7CE"),
                   font=F(10, True, "9C0006")),
        CellIsRule(operator="between", formula=["0.9", "1"], fill=PatternFill("solid", fgColor="FFEB9C"),
                   font=F(10, color="9C6500")),
        CellIsRule(operator="lessThan", formula=["0.9"], fill=PatternFill("solid", fgColor="C6EFCE"),
                   font=F(10, color="006100")),
    ):
        ws.conditional_formatting.add(f"F{sr0+1}:F{sr1}", rule)
    ws.cell(row=sr1 + 1, column=2,
            value="Commitable comes from 'Sprint Plan' column K, so this block is the same capacity test as the "
                  "plan itself — only measured in stories you can actually pull, not in spread epic points.").font = F(9, color="404040", it=True)

    ws.freeze_panes = "D4"
    # Depending on the openpyxl version the chart either survives the load or is dropped.
    # Rebuild it only when it is actually missing, or the Dashboard ends up with two.
    db = wb["Dashboard"]
    charts = len(db._charts)
    if not charts:
        add_dashboard_chart(db)
    wb.save(WB)
    print(f"wrote '{SHEET}': {len(stories)} stories, rows {r0}-{r1} | epic block {er0+1}-{er1} | "
          f"sprint block {sr0+1}-{sr1} | dashboard chart "
          f"{'preserved' if charts else 'rebuilt (round-trip dropped it)'}")
    return 0


# ---------------------------------------------------------------- check
def cmd_check(args):
    m = read_model(WB)
    epics = {e["id"]: e for e in m["epics"]}
    sprints = {s["n"]: s for s in m["sprints"]}
    wb = load_workbook(WB)
    if SHEET not in wb.sheetnames:
        print(f"error: no '{SHEET}' tab yet — run `stories.py write --input FILE.json` first", file=sys.stderr)
        return 2
    ws = wb[SHEET]

    rows = []
    r = 4
    while ws.cell(row=r, column=1).value and ws.cell(row=r, column=2).value:
        rows.append(dict(row=r, id=ws.cell(row=r, column=1).value, epic=ws.cell(row=r, column=2).value,
                         story=ws.cell(row=r, column=4).value, acceptance=ws.cell(row=r, column=5).value,
                         points=ws.cell(row=r, column=7).value, sprint=ws.cell(row=r, column=8).value))
        r += 1

    fail, warn = [], []
    for s in rows:
        if s["epic"] not in epics:
            fail.append(f"{s['id']}: epic {s['epic']} is not on 'Annual Plan'")
            continue
        e = epics[s["epic"]]
        p = s["points"]
        if p is None:
            fail.append(f"{s['id']}: no points")
        elif p not in POINT_SCALE:
            warn.append(f"{s['id']}: {p} points is off the scale {POINT_SCALE}")
        elif p > MAX_STORY_POINTS:
            fail.append(f"{s['id']}: {p} points is above the {MAX_STORY_POINTS}-point ceiling — split it")
        if not s["acceptance"]:
            warn.append(f"{s['id']}: no acceptance criteria")
        if s["sprint"] is None:
            warn.append(f"{s['id']}: not assigned to a sprint")
        elif e["start_sprint"] and not (e["start_sprint"] <= s["sprint"] <= e["end_sprint"]):
            fail.append(f"{s['id']}: sprint {s['sprint']} is outside epic {e['id']}'s range "
                        f"S{e['start_sprint']:02d}-S{e['end_sprint']:02d}")

    print(f"workbook: {WB}")
    print(f"stories: {len(rows)} | epics covered: {len({s['epic'] for s in rows})} of {len(epics)}\n")
    print(f"{'epic':<8} {'estimate':>9} {'stories':>8} {'points':>8} {'variance':>9} {'var %':>7}  verdict")
    for eid, e in epics.items():
        mine = [s for s in rows if s["epic"] == eid]
        if not mine:
            warn.append(f"{eid}: no stories yet")
            print(f"{eid:<8} {e['estimate']:>9.1f} {0:>8} {0:>8.1f} {'':>9} {'':>7}  no stories")
            continue
        pts = sum(s["points"] or 0 for s in mine)
        var = pts - e["estimate"]
        pct = var / e["estimate"] if e["estimate"] else 0
        ok = abs(pct) <= TOLERANCE
        if not ok:
            warn.append(f"{eid}: stories total {pts:.1f} vs estimate {e['estimate']:.1f} ({pct:+.1%})")
        print(f"{eid:<8} {e['estimate']:>9.1f} {len(mine):>8} {pts:>8.1f} {var:>+9.1f} {pct:>+7.1%}  "
              f"{'ok' if ok else 'OUT OF TOLERANCE'}")

    print(f"\n{'sprint':<8} {'commitable':>11} {'assigned':>9} {'load':>7}  stories")
    for n in sorted({s["sprint"] for s in rows if s["sprint"]}):
        pts = sum(s["points"] or 0 for s in rows if s["sprint"] == n)
        comm = sprints[n]["commitable_pts"]
        load = pts / comm if comm else 0
        if load > 1:
            warn.append(f"S{n:02d}: assigned stories {pts:.1f} exceed commitable {comm:.1f} ({load:.1%})")
        print(f"S{n:02d}{'':<5} {comm:>11.1f} {pts:>9.1f} {load:>7.1%}  "
              f"{len([s for s in rows if s['sprint'] == n])}")

    print("\nFAIL" if fail else "\nno blocking problems")
    for x in fail:
        print(f"  FAIL  {x}")
    for x in warn:
        print(f"  warn  {x}")
    return 1 if fail else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("epics", help="dump epics and sprint capacity as JSON")
    w = sub.add_parser("write", help="(re)build the Stories tab from a JSON file")
    w.add_argument("--input", required=True)
    sub.add_parser("check", help="reconcile the Stories tab against epics and capacity")
    args = ap.parse_args()
    return {"epics": cmd_epics, "write": cmd_write, "check": cmd_check}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
